        if (typeof myLandmarks !== 'undefined') {
            localStorage.setItem('hyobin_markers', JSON.stringify(myLandmarks));
        }

        // 모달창 강제로 닫기
        var modal = document.getElementById('bus-stop-modal');
        if (modal) modal.style.display = 'none'; 
        
