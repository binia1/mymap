    // 10. 자동 생성된 상권 마커 초기화 함수
    window.clearGeneratedCommercialMarkers = function(isSilent) {
        if (typeof activeMarkers !== 'undefined' && window.generatedCommercialMarkers && window.generatedCommercialMarkers.length > 0) {
            var genNames = new Set(window.generatedCommercialMarkers.map(g => g.name));
            for (var i = activeMarkers.length - 1; i >= 0; i--) {
                var mk = activeMarkers[i];
                var tip = mk.getTooltip() ? mk.getTooltip().getContent() : "";
                var bMatch = tip.match(/<b>(.*?)<\/b>/);
                var mName = bMatch ? bMatch[1].trim() : "";
                if (mName && genNames.has(mName)) {
                    if (mk.parentGroupLayer) mk.parentGroupLayer.removeLayer(mk);
                    if (typeof subCatFilterLayer !== 'undefined') subCatFilterLayer.removeLayer(mk);
                    map.removeLayer(mk);
                    activeMarkers.splice(i, 1);
                }
            }
        }
        if (typeof allLandmarks !== 'undefined') {
            window.allLandmarks = allLandmarks.filter(m => !m.isAutoCommercial);
            allLandmarks = window.allLandmarks;
        }
        window.generatedCommercialMarkers = [];
        refresh100CategoryWheelCounts();
        if (!isSilent) alert("🗑️ 자동 생성된 상권 마커가 초기화되었습니다.");
    };

    // 11. 좌측 100대 세부 카테고리 휠 카운트 실시간 업데이트
    function refresh100CategoryWheelCounts() {
        var selEl = document.getElementById('subcat-100-wheel-select');
        if (!selEl || typeof activeMarkers === 'undefined' || typeof categoryNames100 === 'undefined') return;

        var counts = {};
        var totalNormal = 0;
        activeMarkers.forEach(function(m) {
            if (m.subCategory) {
                counts[m.subCategory] = (counts[m.subCategory] || 0) + 1;
                totalNormal++;
            }
        });

        var sortedKeys = Object.keys(categoryNames100).sort(function(a, b) {
            return categoryNames100[a].localeCompare(categoryNames100[b], 'ko');
        });

        var optionsHtml = `
            <option value="NONE" selected style="font-weight:bold; color:#555; padding:4px;">🚫 세부 필터 끄기 (우측 체크박스 기준)</option>
            <option value="ALL" style="font-weight:bold; color:#0077DD; padding:4px;">🌐 전체 시설 마커 모두 켜기 (${totalNormal.toLocaleString()}개)</option>
        `;
        sortedKeys.forEach(function(k) {
            var cnt = counts[k] || 0;
            if (cnt > 0) {
                optionsHtml += `<option value="${k}" style="padding:4px; border-bottom:1px solid #f4f4f4; font-weight:500;">▪ ${categoryNames100[k]} (${cnt.toLocaleString()})</option>`;
            }
        });
        sortedKeys.forEach(function(k) {
            var cnt = counts[k] || 0;
            if (cnt === 0) {
                optionsHtml += `<option value="${k}" style="padding:4px; color:#aaa;">▫ ${categoryNames100[k]} (0)</option>`;
            }
        });
        selEl.innerHTML = optionsHtml;
    }

