    function generateSmartStoreName(catKey, brand, adminDong, legalDong, lat, lng, usedFullNames, brandDongCounter, pureLandmarks, addrObj) {
        var cleanAdmin = (adminDong || "").replace(/\(.*\)/g, "").trim();
        var cleanLegal = (legalDong || "").replace(/\(.*\)/g, "").trim();
        if (adminDong.includes("앵내출장소")) cleanLegal = "앵내리";

        // ★ 핵심: 읍/면 지역이거나 행정동과 법정동 이름이 다를 때 법정리/법정동(예: 요우리, 고무리, 탄자동, 사노동) 이름을 1순위로 사용!
        var primaryLocalName = cleanLegal || cleanAdmin;
        var primaryShort = primaryLocalName.replace(/(동|리)$/, '');
        if (primaryShort.length <= 1) primaryShort = primaryLocalName; // '공리', '입리', '등동' 등은 글자 유지

        var bdKey = brand + "_" + primaryLocalName;
        var countInArea = brandDongCounter[bdKey] || 0;
        brandDongCounter[bdKey] = countInArea + 1;

        var nearLandmarks = [];
        for (var i = 0; i < pureLandmarks.length; i++) {
            var lm = pureLandmarks[i];
            var d = Math.sqrt(Math.pow(lm.lat - lat, 2) + Math.pow(lm.lng - lng, 2));
            if (d <= 900) {
                nearLandmarks.push({ name: lm.cleanBranchName, rawName: lm.name, type: lm.type, dist: d });
            }
        }
        nearLandmarks.sort((a, b) => a.dist - b.dist);

        var roadClean = (addrObj && addrObj.roadAddress) ? (addrObj.roadAddress.split(" ").pop().replace(/\d+.*$/, "").trim()) : "중앙로";
        var branchCandidates = [];

        // 1순위: 법정리 / 법정동 지명! (예: 요우리, 고무리, 신산리 / 동 지역은 행정동·법정동)
        if (cleanLegal.endsWith("리")) {
            branchCandidates.push(cleanLegal);       // 예: '요우리', '고무리'
            branchCandidates.push(cleanAdmin + cleanLegal.replace(/리$/, '')); // 예: '도변읍요우'
            branchCandidates.push(cleanAdmin.replace(/(읍|면)$/, '') + cleanLegal); // 예: '도변요우리'
            branchCandidates.push(cleanAdmin);       // 예: '도변읍'
        } else {
            branchCandidates.push(cleanLegal);       // 예: '탄자동', '사노동', '고송동'
            if (cleanAdmin !== cleanLegal) {
                branchCandidates.push(cleanAdmin);   // 예: '이자3동', '고송1동'
            }
        }

        // 2순위: 주변 주요 랜드마크(지하철역, 학교, 청사, 아파트, 공원 등) 이름
        nearLandmarks.forEach(function(nl) {
            if (nl.name && !branchCandidates.includes(nl.name)) {
                branchCandidates.push(nl.name);
                if (nl.type === 'subway' || nl.name.endsWith('역')) {
                    branchCandidates.push(nl.name + "앞");
                } else if (nl.name.match(/(초교|중교|고교|여고|여중|대|과기원)$/)) {
                    branchCandidates.push(nl.name + "앞");
                    branchCandidates.push(nl.name + "사거리");
                } else if (nl.name.match(/(시청|구청|군청|법원|세무서|경찰서|소방서)$/)) {
                    branchCandidates.push(nl.name + "앞");
                }
            }
        });

        // 3순위: 도로명 및 방위 접미사
        if (roadClean && roadClean.length >= 2) {
            branchCandidates.push(primaryLocalName + roadClean);
        }
        var suffixes = ["중앙", "역세권", "센트럴", "북부", "남부", "동부", "서부", "광장", "타운", "스퀘어", "2호", "3호"];
        suffixes.forEach(function(sfx) {
            branchCandidates.push(primaryLocalName + sfx);
            if (cleanAdmin !== primaryLocalName) branchCandidates.push(cleanAdmin + sfx);
        });

        for (var c = 0; c < branchCandidates.length; c++) {
            var br = branchCandidates[c];
            if (!br) continue;
            var fullCandidate = formatStoreTitle(catKey, brand, br);
            if (!usedFullNames.has(fullCandidate)) {
                usedFullNames.add(fullCandidate);
                return fullCandidate;
            }
        }

        var fallbackName = formatStoreTitle(catKey, brand, primaryLocalName + (countInArea + 1) + "호");
        usedFullNames.add(fallbackName);
        return fallbackName;
    }

