    function lockMasterReviewEngine() {
        fixSaemaulAndCategoryBug();

        var currentGenMulti = window.generateMultipleReviews;
        if (!currentGenMulti || !currentGenMulti._isMasterHooked) {
            var baseFn = currentGenMulti;
            var wrappedFn = function(ratingScore, type, name, customDesc, targetReviewCount) {
                return buildMasterReviewList(ratingScore, type, name, customDesc, targetReviewCount, baseFn);
            };
            wrappedFn._isMasterHooked = true;
            window.generateMultipleReviews = wrappedFn;
        }

        // 상세페이지 새 창에서 리뷰 작성 & 공감 버튼이 즉시 작동하도록 openDetailWindow 업그레이드
        if (typeof window.openDetailWindow === 'function' && !window.openDetailWindow._isMasterDetailHooked) {
            var origOpenDetail = window.openDetailWindow;
            var wrappedDetail = function(encodedData) {
                try {
                    var data = JSON.parse(decodeURIComponent(encodedData));
                    var latestItem = (typeof myLandmarks !== 'undefined' && myLandmarks.find(m => m.name === data.name)) ||
                                     (typeof allLandmarks !== 'undefined' && allLandmarks.find(m => m.name === data.name));
                    if (latestItem) {
                        if (latestItem.rating !== undefined) data.rating = latestItem.rating;
                        if (latestItem.reviews !== undefined) data.reviews = latestItem.reviews;
                        if (latestItem.desc !== undefined) data.desc = latestItem.desc;
                        if (latestItem.type !== undefined) data.type = latestItem.type;
                    }
                    // 새마을금고면 강제 교정
                    if (data.name && data.name.includes("새마을금고")) {
                        data.type = "credit_union";
                        data.typeName = "새마을금고·신협·단위농협";
                    }
                    encodedData = encodeURIComponent(JSON.stringify(data));
                } catch (e) {}

                // 원본 openDetailWindow의 window.open을 가로채서 공감/리뷰작성 스크립트를 새 창에 주입!
                var origWinOpen = window.open;
                window.open = function() {
                    var win = origWinOpen.apply(this, arguments);
                    if (win) {
                        var origDocClose = win.document.close;
                        win.document.close = function() {
                            origDocClose.apply(this, arguments);
                            try {
                                injectInteractiveReviewFeaturesIntoDetailWindow(win, encodedData);
                            } catch (err) { console.error(err); }
                        };
                    }
                    return win;
                };
                try {
                    origOpenDetail(encodedData);
                } finally {
                    window.open = origWinOpen;
                }
            };
            wrappedDetail._isMasterDetailHooked = true;
            window.openDetailWindow = wrappedDetail;
        }
    }

