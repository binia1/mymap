    function isForbiddenIslandCoord(lat, lng, adminName, legalName) {
        var rawLat = lat - ADJ_Y; // 보정 전 원본 Y좌표로 역산하여 정확히 판별
        var aName = (adminName || "").trim();
        var lName = (legalName || "").trim();

        // 1) 북구 포산동 북쪽 섬(포상도: rawLat -900 ~ -2000 부근) 완벽 차단!
        if ((aName.includes("포산") || lName.includes("포산")) && rawLat > -2500) {
            return true;
        }
        // 2) 창전구 팔조동 남쪽 섬(개비도: rawLat -18500 ~ -20000 부근) 완벽 차단!
        if ((aName.includes("팔조") || lName.includes("팔조")) && rawLat < -18000) {
            return true;
        }
        // 3) 중구 내항동 외딴 작은 섬(rawLat -7300 ~ -7600, lng 11700 ~ 12000) 차단!
        if ((aName.includes("내항") || lName.includes("내항")) && rawLat > -8000) {
            return true;
        }
        return false;
    }

    function getRingArea(ring) {
        if (!ring || ring.length < 3) return 0;
        var sum = 0;
        for (var i = 0; i < ring.length; i++) {
            var p1 = ring[i], p2 = ring[(i + 1) % ring.length];
            sum += (p1[1] * p2[0] - p2[1] * p1[0]);
        }
        return Math.abs(sum) / 2;
    }

    // MultiPolygon(본토 + 섬)에서 섬 링을 버리고 가장 큰 본토(Mainland) 링만 남긴 폴리곤 반환
    function getMainlandPolygonObj(polyObj, adminDong, legalDong) {
        if (!polyObj || !polyObj.points || polyObj.points.length === 0) return null;
        var isMulti = Array.isArray(polyObj.points[0][0]);
        if (!isMulti) return polyObj;

        var validRings = polyObj.points.filter(function(ring) {
            if (!ring || ring.length < 3) return false;
            var p0 = ring[0];
            return !isForbiddenIslandCoord(p0[0], p0[1], adminDong, legalDong);
        });

        if (validRings.length === 0) validRings = polyObj.points;

        // 가장 면적이 큰 본토 링을 대표 링으로 선택 (행정동+법정동 분할 지역 대응)
        validRings.sort(function(a, b) { return getRingArea(b) - getRingArea(a); });
        return {
            name: polyObj.name,
            type: polyObj.type,
            points: [validRings[0]]
        };
    }

