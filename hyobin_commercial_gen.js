    function pickWeightedBrand(catKey) {
        var pool = weightedBrandPools[catKey];
        if (!pool || pool.length === 0) return "일반매장";
        var totalWeight = 0;
        for (var i = 0; i < pool.length; i++) {
            totalWeight += pool[i].w;
        }
        var r = seededRandom() * totalWeight;
        var accum = 0;
        for (var j = 0; j < pool.length; j++) {
            accum += pool[j].w;
            if (r <= accum) {
                return pool[j].b;
            }
        }
        return pool[pool.length - 1].b;
    }

